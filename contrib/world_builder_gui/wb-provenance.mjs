function oneLine(value) {
  return String(value ?? "").replace(/\s+/g, " ").trim();
}

export function stripJsonComments(text) {
  let output = "";
  let inString = false;
  let escaped = false;
  let lineComment = false;
  let blockComment = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    const next = text[index + 1];
    if (lineComment) {
      if (character === "\n") {
        lineComment = false;
        output += character;
      }
      continue;
    }
    if (blockComment) {
      if (character === "*" && next === "/") {
        blockComment = false;
        index += 1;
      } else if (character === "\n") {
        output += character;
      }
      continue;
    }
    if (inString) {
      output += character;
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === "\"") inString = false;
      continue;
    }
    if (character === "\"") {
      inString = true;
      output += character;
    } else if (character === "/" && next === "/") {
      lineComment = true;
      index += 1;
    } else if (character === "/" && next === "*") {
      blockComment = true;
      index += 1;
    } else {
      output += character;
    }
  }
  return output;
}

export function parseWorldBuilderText(text) {
  return JSON.parse(stripJsonComments(text));
}

export function serializeWorldBuilder(world, provenance = {}, options = {}) {
  const includeComments = options.includeComments !== false;
  const includeReferences = options.includeReferences !== false;
  if (!includeComments) return `${JSON.stringify(world, null, 2)}\n`;

  const lines = [
    "// Generated by Geodynamic World Builder Visual Builder.",
    "// GWB accepts // comments; strict JSON readers may require comments to be removed."
  ];
  (provenance.notes || []).map(oneLine).filter(Boolean)
    .forEach(note => lines.push(`// ${note}`));

  if (includeReferences && provenance.references?.length) {
    lines.push("//");
    lines.push("// References and data provenance:");
    provenance.references.forEach(reference => {
      const citation = oneLine(reference.citation || reference.name);
      const url = oneLine(reference.citationUrl || reference.sourceUrl);
      lines.push(`// - ${citation}${url ? ` ${url}` : ""}`);
      if (reference.sourceUrl && reference.sourceUrl !== url) {
        lines.push(`//   Data: ${oneLine(reference.sourceUrl)}`);
      }
    });
  }
  return `${lines.join("\n")}\n${JSON.stringify(world, null, 2)}\n`;
}
